on public.league_matchup_lineups
for insert
to authenticated
with check (
  exists (
    select 1
    from public.league_memberships as membership
    where membership.league_id = league_matchup_lineups.league_id
      and membership.user_id = auth.uid()
      and membership.league_team_id = league_matchup_lineups.team_id
  )
);

