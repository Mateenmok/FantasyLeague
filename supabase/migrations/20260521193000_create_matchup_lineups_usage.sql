create or replace function public.get_matchup_lineup_status(
  target_league_id text,
  target_matchup_id text
)
returns table(team_id text, selected_count bigint)
language sql
security definer
set search_path = public
as $$
  select lineup.team_id, count(*)::bigint as selected_count
  from public.league_matchup_lineups as lineup
  where lineup.league_id = target_league_id
    and lineup.matchup_id = target_matchup_id
    and exists (
      select 1
      from public.league_memberships as membership
      where membership.league_id = target_league_id
        and membership.user_id = auth.uid()
    )
  group by lineup.team_id;
$$;

create or replace function public.can_read_matchup_lineup(
  target_league_id text,
  target_matchup_id text,
  target_team_id text
)
returns boolean
language sql
security definer
set search_path = public
as $$
  with membership as (
    select league_team_id
    from public.league_memberships
    where league_id = target_league_id
      and user_id = auth.uid()
    limit 1
  ),
  lineup_counts as (
    select team_id, count(*)::integer as selected_count
    from public.league_matchup_lineups
    where league_id = target_league_id
      and matchup_id = target_matchup_id
    group by team_id
  ),
  reveal_ready as (
    select coalesce(count(*) = 2 and bool_and(selected_count >= 6), false) as is_ready
    from lineup_counts
  )
  select exists (select 1 from membership)
    and (
      exists (select 1 from membership where league_team_id = target_team_id)
      or exists (select 1 from reveal_ready where is_ready)
    );
$$;

grant execute on function public.get_matchup_lineup_status(text, text) to authenticated;
grant execute on function public.can_read_matchup_lineup(text, text, text) to authenticated;

